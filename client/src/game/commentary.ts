export type ReactionKind = keyof typeof reactionLines;
export interface Commentary {
  text: string;
  kind: ReactionKind;
  serial: number;
  lastAt: number;
  lastMoveAt: number;
  lastProgressAt: number;
  streak: number;
  seen: string[];
  milestones: string[];
}
export const emptyCommentary = (): Commentary => ({
  text: "",
  kind: "start",
  serial: 0,
  lastAt: 0,
  lastMoveAt: 0,
  lastProgressAt: 0,
  streak: 0,
  seen: [],
  milestones: [],
});

function speak(
  game: Game,
  kind: ReactionKind,
  now: number,
  force = false,
  milestone?: string,
): Game {
  const state = game.commentary;
  if (!force && now - state.lastAt < 6500) return game;
  const pool = reactionLines[kind];
  let choices = pool.map((text, index) => ({ text, id: `${kind}:${index}` }));
  const fresh = choices.filter(({ id }) => !state.seen.includes(id));
  // При исчерпании банка берём наименее недавно звучавшую реплику.
  if (fresh.length) choices = fresh;
  else
    choices = [
      choices.reduce((a, b) =>
        state.seen.indexOf(a.id) < state.seen.indexOf(b.id) ? a : b,
      ),
    ];
  const hash =
    (Math.imul(game.seed ^ (state.serial + 1), 1664525) + 1013904223) >>> 0;
  const line = choices[hash % choices.length];
  return {
    ...game,
    commentary: {
      ...state,
      text: line.text,
      kind,
      serial: state.serial + 1,
      lastAt: now,
      seen: [...state.seen.filter((id) => id !== line.id), line.id].slice(-100),
      milestones: milestone
        ? [...state.milestones, milestone].slice(-40)
        : state.milestones,
    },
  };
}

export function observe(
  previous: Game,
  next: Game,
  action: Action,
  now: number,
): Game {
  const active = next.phase === "playing" && next.runningSince !== null;
  const wasActive =
    previous.phase === "playing" && previous.runningSince !== null;
  if (previous.failedAttempts < next.failedAttempts)
    return speak(next, "mistake", now, true);
  if (!active) return next;
  if (!wasActive) {
    const fresh = {
      ...next,
      commentary: {
        ...next.commentary,
        lastMoveAt: now,
        lastProgressAt: now,
        streak: 0,
      },
    };
    const bonus =
      next.bonusGranted && !next.commentary.milestones.includes("bonus:start");
    const kind = bonus
      ? "bonus"
      : next.failedAttempts >= (next.bonusGranted ? 5 : 4)
        ? "lastChance"
        : previous.phase === "retry"
          ? "retry"
          : next.encoreGranted
            ? "encore"
            : "start";
    return speak(fresh, kind, now, true, bonus ? "bonus:start" : undefined);
  }

  let game = next;
  const opened = next.board.revealed.length - previous.board.revealed.length;
  const flagsChanged = next.board.flags.length !== previous.board.flags.length;
  if (opened > 0 || flagsChanged) {
    const streak =
      opened > 0 && now - previous.commentary.lastMoveAt < 2600
        ? previous.commentary.streak + 1
        : opened > 0
          ? 1
          : 0;
    game = {
      ...next,
      commentary: {
        ...next.commentary,
        lastMoveAt: now,
        lastProgressAt: opened > 0 ? now : next.commentary.lastProgressAt,
        streak,
      },
    };
  }
  const state = game.commentary;
  const time = game.remaining - Math.max(0, now - game.runningSince!);
  const segment = game.bonusGranted ? "bonus" : "main";
  // Срочные реакции важнее шутки о ходе, но не перебивают сами себя каждый тик.
  for (const [threshold, kind] of [
    [15000, "time15"],
    [45000, "time45"],
    [90000, "time90"],
  ] as const) {
    const key = `${segment}:${kind}`;
    if (time <= threshold && !state.milestones.includes(key)) {
      // Если вкладка проснулась поздно, устаревшие предупреждения уже не нужны.
      const marked = {
        ...game,
        commentary: {
          ...state,
          milestones: [
            ...state.milestones,
            ...([90000, 45000, 15000] as const)
              .filter((t) => t >= threshold)
              .map(
                (t) =>
                  `${segment}:${t === 90000 ? "time90" : t === 45000 ? "time45" : "time15"}`,
              ),
          ].filter((v, i, a) => a.indexOf(v) === i),
        },
      };
      return speak(marked, kind, now, true);
    }
  }
  if (flagsChanged) {
    return speak(
      game,
      next.board.flags.length < previous.board.flags.length
        ? "unflag"
        : next.board.flags.length === next.board.mineCount
          ? "allFlags"
          : "flag",
      now,
    );
  }
  if (opened > 0) {
    const round = `${game.encoreGranted}:${game.failedAttempts}`;
    const nearKey = `${round}:near`;
    if (
      game.board.revealed.length /
        (game.board.size ** 2 - game.board.mineCount) >=
        0.8 &&
      !state.milestones.includes(nearKey)
    )
      return speak(game, "near", now, false, nearKey);
    if (opened >= 6) return speak(game, "flood", now);
    if (state.streak >= 3) return speak(game, "streak", now);
    if (action.type === "reveal" && adjacentMines(game.board, action.cell) >= 3)
      return speak(game, "numbers", now);
    if (game.failedAttempts > 0 && state.serial % 3 === 0)
      return speak(game, "comeback", now);
    return speak(game, "safe", now);
  }
  if (action.type !== "tick" || now - state.lastAt < 11000) return game;
  const idle = now - state.lastMoveAt;
  if (idle >= 15000 && !game.board.revealed.length)
    return speak(game, "idleStart", now);
  if (idle >= 35000) return speak(game, "longIdle", now);
  if (idle >= 15000) return speak(game, "idle", now);
  if (now - state.lastProgressAt >= 30000) return speak(game, "stalled", now);
  const kinds: ReactionKind[] = ["support", "tease", "meta", game.attitude];
  const kind = kinds[(state.serial + game.seed) % kinds.length];
  return speak(game, kind === state.kind ? "support" : kind, now);
}
