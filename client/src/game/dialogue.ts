export type Attitude = "hero" | "deal" | "chaos" | "detective" | "tired";

export interface Reply {
  text: string;
  next: string;
  attitude?: Attitude;
}

export interface DialogueNode {
  lines: string[];
  replies: Reply[];
}

const reply = (text: string, next: string, attitude?: Attitude): Reply => ({
  text,
  next,
  attitude,
});
const node = (lines: string[], ...replies: Reply[]): DialogueNode => ({
  lines,
  replies,
});

